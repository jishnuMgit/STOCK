-- =====================================================================
-- Beginning / Year Close Balance report
-- Procedure: dbo.sp_rptyearclosebal   (the port of the old SQL Server
-- SP_rptYearCloseBal)
--
-- Used by the Beginning Balance screen (Print) through the report
-- rptYearCloseBalRpt, and by the "Beginning/Year Close Bal." report.
--
-- Parameters, as in the original
--   p_gstrcoid          the company
--   p_rdgbranch         0 = one branch (p_strbrid), anything else = all branches
--   p_strbrid           the branch (used when p_rdgbranch = 0)
--   p_strdoctype        'BG' = the Beginning Balances typed in the Beginning Balance
--                       screen (all years of the branch - the year is not used);
--                       any other value = the Opening Balances ('OP') generated by
--                       the year closing, found by the year AFTER p_intyear
--   p_intyear           the year (only for the 'OP' case, as in the original)
--   p_intaccountlevel   the deepest account level to return (4 = the accounts)
--   p_blnprintacgroup   false = only the accounts of level p_intaccountlevel;
--                       true  = the groups too (levels 1..p_intaccountlevel), the
--                       names indented by level
--
-- What it does, as the original does
--   1. adds up debit - credit of the lines of tblfintrans for each account and cost
--      center (the lines are found by company, document type, branch)
--   2. makes a row for each account (level 4, with its cost center) and a row for
--      each of its parent accounts of levels 3, 2 and 1 (no cost center), the
--      parents found with dbo.getaccountgroupid, each with the sum of its accounts
--   3. a positive sum is a Debit, a negative one a Credit (its absolute value)
--   4. the name and the level come from tblaccount; a row whose account is not in
--      tblaccount keeps level 0, an account with no level (NULL) keeps NULL - and
--      so is not returned by either filter, as in the original
--   5. returns the rows ordered by account id
--
-- Returned columns: fcoid, faccountid, faccountname, faccountlevel, fccid, fdate,
-- fdrcr, fdebit, fcredit.
--
-- The only differences from the SQL Server procedure: no temporary tables and no
-- dynamic SQL (one query with the filter as parameters), and the rows with the
-- same account id are also ordered by cost center.
--
-- Test (cursor calls must run inside one transaction)
--   BEGIN;
--   CALL dbo.sp_rptyearclosebal('01', 0::smallint, 'JD', 'BG', 2026::smallint,
--                               4::smallint, false, p_result_cursor => 'c1');
--   FETCH ALL FROM "c1";
--   COMMIT;
-- =====================================================================

drop procedure if exists dbo.sp_rptyearclosebal(
    varchar, smallint, varchar, varchar, smallint, smallint, boolean, refcursor
);

create or replace procedure dbo.sp_rptyearclosebal(
    in p_gstrcoid varchar(3),
    in p_rdgbranch smallint,
    in p_strbrid varchar(3),
    in p_strdoctype varchar(5),
    in p_intyear smallint,
    in p_intaccountlevel smallint,
    in p_blnprintacgroup boolean,
    inout p_result_cursor refcursor default 'cur_rptyearclosebal'
)
language plpgsql
as $body$
begin

    open p_result_cursor for
        with t as (
            -- the sum of debit - credit of each account and cost center
            select f.fcoid,
                   f.faccountid as faccountid4,
                   f.fccid,
                   min(f.fdate) as fdate,
                   sum(coalesce(f.fdebit, 0) - coalesce(f.fcredit, 0)) as fdrcr
              from dbo.tblfintrans f
             where f.fcoid = p_gstrcoid
               and (
                       (p_strdoctype = 'BG' and f.fdoctype = 'BG')
                    or (p_strdoctype <> 'BG' and f.fdoctype = 'OP'
                        and f.fyear = (p_intyear + 1)::varchar)
                   )
               and (p_rdgbranch <> 0 or f.fbrid = p_strbrid)
             group by f.fcoid, f.faccountid, f.fccid
        ),
        t2 as (
            -- and the parents of each account, levels 1, 2 and 3
            select t.*,
                   dbo.getaccountgroupid(p_gstrcoid, t.faccountid4, 1::smallint) as faccountid1,
                   dbo.getaccountgroupid(p_gstrcoid, t.faccountid4, 2::smallint) as faccountid2,
                   dbo.getaccountgroupid(p_gstrcoid, t.faccountid4, 3::smallint) as faccountid3
              from t
        ),
        u as (
            -- level 4: the accounts, with their cost center
            select fcoid, faccountid4 as faccountid, fccid, min(fdate) as fdate, sum(fdrcr) as fdrcr
              from t2
             group by fcoid, faccountid4, fccid
            union all
            -- levels 3, 2 and 1: the groups
            select fcoid, faccountid3, null::varchar, min(fdate), sum(fdrcr)
              from t2 group by fcoid, faccountid3
            union all
            select fcoid, faccountid2, null::varchar, min(fdate), sum(fdrcr)
              from t2 group by fcoid, faccountid2
            union all
            select fcoid, faccountid1, null::varchar, min(fdate), sum(fdrcr)
              from t2 group by fcoid, faccountid1
        ),
        r as (
            select u.fcoid,
                   u.faccountid,
                   -- a row whose account is not in tblaccount keeps the default level 0
                   case when a.faccountid is null then null else a.faccountname end as faccountname,
                   case when a.faccountid is null then 0 else a.faccountlevel end as faccountlevel,
                   u.fccid,
                   u.fdate,
                   u.fdrcr,
                   case when u.fdrcr > 0 then u.fdrcr else 0 end as fdebit,
                   case when u.fdrcr < 0 then abs(u.fdrcr) else 0 end as fcredit
              from u
              left join dbo.tblaccount a
                on a.fcoid = u.fcoid and a.faccountid = u.faccountid
        )
        select r.fcoid,
               r.faccountid,
               -- with the groups, the name is indented by level (the original did
               -- it with leading spaces)
               case
                   when p_blnprintacgroup and r.faccountlevel = 2 then '    ' || r.faccountname
                   when p_blnprintacgroup and r.faccountlevel = 3 then '        ' || r.faccountname
                   when p_blnprintacgroup and r.faccountlevel = 4 then '            ' || r.faccountname
                   else r.faccountname
               end as faccountname,
               r.faccountlevel,
               r.fccid,
               r.fdate,
               r.fdrcr,
               r.fdebit,
               r.fcredit
          from r
         where (not p_blnprintacgroup and r.faccountlevel = p_intaccountlevel)
            or (p_blnprintacgroup and r.faccountlevel <= p_intaccountlevel)
         order by r.faccountid, r.fccid;

end;
$body$;

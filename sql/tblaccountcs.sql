-- Customer / supplier accounts (one row per company + account id).
-- Taken from a pg_dump of the working database. Used by the customer
-- and supplier lookups (filllookupcustomerid/name, fillsupplier,
-- getcustomerlist, sp_pagescustomer, ...).
